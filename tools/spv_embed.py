"""Embeds a SPIR-V binary as a C array: craw_<name>_spv_data[] / craw_<name>_spv_len."""
import sys

def main():
    spv_path, out_path, name = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(spv_path, "rb") as f:
        data = f.read()
    with open(out_path, "w") as f:
        f.write("/* Generated by spv_embed.py, do not edit. */\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n")
        f.write(f"static const uint8_t craw_{name}_spv_data[] __attribute__((aligned(4))) = {{\n")
        for i in range(0, len(data), 16):
            f.write("    " + ",".join(str(b) for b in data[i:i+16]) + ",\n")
        f.write("};\n")
        f.write(f"static const size_t craw_{name}_spv_len = {len(data)};\n")

if __name__ == "__main__":
    main()
