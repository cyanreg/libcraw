"""Embeds an arbitrary binary as a C array: <name>_data[] / <name>_len.

The same idea as spv_embed.py, but that one hardcodes the craw_<name>_spv_
naming and four-byte alignment for SPIR-V. This takes the symbol prefix as
an argument and aligns to eight bytes, which is enough for any of the
fixed-width integer and float fields a packed blob is read back through.

Usage: blob_embed.py INPUT OUTPUT SYMBOL
"""
import sys


def main():
    in_path, out_path, name = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(in_path, "rb") as f:
        data = f.read()
    with open(out_path, "w") as f:
        f.write("/* Generated by blob_embed.py from %s, do not edit. */\n"
                % in_path.rsplit("/", 1)[-1])
        f.write("#include <stddef.h>\n#include <stdint.h>\n")
        f.write("static const uint8_t %s_data[] __attribute__((aligned(8))) "
                "= {\n" % name)
        for i in range(0, len(data), 16):
            f.write("    " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write("static const size_t %s_len = %d;\n" % (name, len(data)))


if __name__ == "__main__":
    main()
